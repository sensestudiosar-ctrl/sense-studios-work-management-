from playwright.sync_api import sync_playwright
from pathlib import Path
h=(Path(__file__).resolve().parents[1]/'index.html').read_text()
checks=[]
def ck(name,flag):
 checks.append((name,bool(flag)));print(('PASS' if flag else 'FAIL'),name)
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 cx=b.new_context(viewport={'width':1440,'height':900})
 page=cx.new_page();js=[];page.on('pageerror',lambda e:js.append(str(e)))
 page.goto('about:blank')
 page.evaluate('''() => {const m={};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>m[k]??null,setItem:(k,v)=>m[k]=String(v),removeItem:k=>delete m[k],clear:()=>{for(const k in m)delete m[k]}}})}''')
 page.set_content(h,wait_until='domcontentloaded');page.wait_for_timeout(500)
 ck('defaults Owner four widgets',page.locator('.dash-unit').count()==4)
 ck('cards remain fixed outside grid',page.locator('.summary-grid .summary-card').count()==5 and page.locator('.dash-unit .summary-card').count()==0)
 ck('bottom attention outside drag grid',page.locator('.attention-bottom').count()==1 and page.locator('#dashboard-flow .attention-bottom').count()==0)
 page.locator('[data-action="start-edit"]').first.click();page.wait_for_timeout(550)
 ck('editor shows move handles',page.locator('[data-widget-grip]').count()==4)
 ck('gallery starts collapsed',page.locator('.v9-widget-gallery').get_attribute('open') is None)
 initial=page.locator('.dashboard-lane[data-lane="left"] .dash-unit').evaluate_all('(x)=>x.map(e=>e.dataset.unit)')
 # cross lane drag using HTML5
 source=page.locator('[data-widget-grip="time"]');target=page.locator('[data-widget-grip="decisions"]')
 source.drag_to(target,force=True);page.wait_for_timeout(300)
 now=page.locator('.dashboard-lane[data-lane="right"] .dash-unit').evaluate_all('(x)=>x.map(e=>e.dataset.unit)')
 print('After mouse drag',now)
 ck('desktop native drag repositions tile', 'time' in now)
 # read persisted position then force reload preference into role memory
 page.evaluate('delete ui.widgetPrefs.owner;renderApp()');page.wait_for_timeout(200)
 persisted=page.locator('.dashboard-lane[data-lane="right"] .dash-unit').evaluate_all('(x)=>x.map(e=>e.dataset.unit)')
 ck('custom order restored from persistence', 'time' in persisted)
 page.locator('[data-widget-hide="projects"]').click();page.wait_for_timeout(130)
 ck('hide removes tile immediately',page.locator('[data-unit="projects"]').count()==0)
 ck('hidden remains addable',page.locator('[data-widget-add="projects"]').count()==1)
 page.locator('.v9-widget-gallery summary').click();page.locator('[data-widget-add="projects"]').click();page.wait_for_timeout(150)
 ck('add restores permitted tile',page.locator('[data-unit="projects"]').count()==1)
 page.select_option('#demo-persona','cross');page.wait_for_timeout(300)
 page.locator('[data-action="start-edit"]').first.click();page.wait_for_timeout(200)
 ck('Cross branch cannot add performance or decisions',page.locator('[data-widget-add="performance"]').count()==0 and page.locator('[data-widget-add="decisions"]').count()==0)
 page.select_option('#demo-persona','owner');page.wait_for_timeout(320)
 ck('Owner settings separate from cross',page.locator('[data-unit="performance"]').count()==1)
 page.locator('[data-action="start-edit"]').first.click();page.wait_for_timeout(90)
 page.locator('[data-action="reset-widgets"]').first.click();page.wait_for_timeout(200)
 ck('reset restores four defaults',page.locator('.dash-unit').count()==4)
 ck('no page JS errors',not js);print('page JS errors',js)
 cx.close()
 # pointer touch simulated
 cx=b.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
 page=cx.new_page();page.goto('about:blank');page.set_content(h,wait_until='domcontentloaded');page.wait_for_timeout(550)
 page.locator('[data-action="start-edit"]').first.click();page.wait_for_timeout(550)
 before=page.locator('#dashboard-flow .dash-unit').evaluate_all('(x)=>x.map(e=>e.dataset.unit)')
 # scroll to drag handles
 page.locator('[data-widget-grip="time"]').scroll_into_view_if_needed()
 page.evaluate('''()=>{const source=document.querySelector('[data-widget-grip="time"]');const t=document.querySelector('[data-widget-grip="decisions"]');const a=source.getBoundingClientRect(),b=t.closest('.dash-unit').getBoundingClientRect();source.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:7,pointerType:'touch',clientX:a.x+20,clientY:a.y+12}));document.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,pointerId:7,pointerType:'touch',clientX:b.x+30,clientY:b.top+b.height*.70}));document.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerId:7,pointerType:'touch',clientX:b.x+30,clientY:b.top+b.height*.70}));}''');page.wait_for_timeout(300)
 after=page.locator('#dashboard-flow .dash-unit').evaluate_all('(x)=>x.map(e=>e.dataset.unit)')
 print('touch move',before,'->',after)
 ck('mobile pointer drag reorders',before!=after)
 ck('mobile no overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 cx.close();b.close()
print('SUMMARY',sum(x for _,x in checks),'/',len(checks))
