import { test, expect } from "@playwright/test";
import { isS27DisposableTestTarget, matchesS27DisposableServer } from "../../apps/api/src/s27-disposable-test-target.js";
import { createHash, createHmac, randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const fixtureUrl = process.env.DATABASE_URL ?? process.env.S16_ADMIN_DATABASE_URL;
const disposableS27Database = Boolean(process.env.DATABASE_URL && isS27DisposableTestTarget("DATABASE_URL", process.env.DATABASE_URL));
const receiverUrl = process.env.TIME_ACCOUNTING_RECEIVER_URL;
const receiverToken = process.env.S16_TEST_RECEIVER_TOKEN;

test("time workspace persists timer and manual work through correction, approval, export and retry", async ({ page, context, baseURL }, testInfo) => {
  test.setTimeout(120_000);
  test.skip(!fixtureUrl || !receiverUrl || !receiverToken || process.env.S16_E2E_ENABLED !== "1", "Dedicated S16 database and real loopback accounting receiver are required");
  const parsed = new URL(fixtureUrl!);
  const explicitlyEnabledS25Database = process.env.S25_E2E_ENABLED === "1" && ["localhost", "127.0.0.1"].includes(parsed.hostname) && ((["56433", "57433"].includes(parsed.port) && /^\/sense_s25_main_s25_[a-z0-9_]+_test$/i.test(parsed.pathname)) || (parsed.port === "57433" && /^\/sense_s16_s25_[a-z0-9_]+_test$/i.test(parsed.pathname)));
  const explicitlyEnabledS26Database = process.env.S26_E2E_ENABLED === "1" && ["localhost", "127.0.0.1"].includes(parsed.hostname) && parsed.port === "57433" && /^\/sense_s26_main_s26_[a-z0-9_]+_test$/i.test(parsed.pathname);
  const explicitlyEnabledS27Database = process.env.S27_E2E_ENABLED === "1" && parsed.hostname === "127.0.0.1" && parsed.port === "57433" && /^\/sense_s27_main_s27_[a-z0-9_]+_test$/.test(parsed.pathname) || disposableS27Database;
  if (!["localhost", "127.0.0.1"].includes(parsed.hostname) || ((!explicitlyEnabledS25Database && !explicitlyEnabledS26Database && !explicitlyEnabledS27Database) && parsed.port !== "56433") || (!parsed.pathname.endsWith("_test") && !explicitlyEnabledS25Database && !explicitlyEnabledS26Database && !explicitlyEnabledS27Database)) {
    throw new Error("Time browser acceptance requires a dedicated local PostgreSQL _test database on an approved S16 or exact S25 target");
  }
  const receiver = new URL(receiverUrl!);
  if (!["localhost", "127.0.0.1", "::1"].includes(receiver.hostname)) throw new Error("S16 E2E accounting receiver must be loopback");
  const require = createRequire(resolve("apps/api/package.json"));
  const { Client } = require("pg") as typeof import("pg");
  const db = new Client({ connectionString: fixtureUrl });
  const suffix = randomUUID();
  const digest = (value: string) => createHash("sha256").update(value).digest("hex");
  const staffSecret = randomBytes(32).toString("base64url");
  const managerSecret = randomBytes(32).toString("base64url");
  const ownerSecret = randomBytes(32).toString("base64url");
  const staffCsrf = createHmac("sha256", staffSecret).update("csrf").digest("base64url");
  const managerCsrf = createHmac("sha256", managerSecret).update("csrf").digest("base64url");
  const ownerCsrf = createHmac("sha256", ownerSecret).update("csrf").digest("base64url");
  const staffAccountId = randomUUID(), managerAccountId = randomUUID();
  let ownerAccountId: string;
  const staffEmployeeId = randomUUID(), managerEmployeeId = randomUUID();
  const branchId = randomUUID(), teamId = randomUUID();
  const staffSessionId = randomUUID(), managerSessionId = randomUUID(), ownerSessionId = randomUUID();
  const timerNote = `S16 timer ${suffix}`;
  const manualNote = `S16 manual ${suffix}`;
  const correctedNote = `S16 correction ${suffix}`;

  await db.connect();
  if (disposableS27Database) {
    const identity = await db.query<{ database: string; port: number }>("SELECT current_database() AS database, inet_server_port() AS port");
    if (!matchesS27DisposableServer(process.env.DATABASE_URL!, identity.rows[0]!.database, identity.rows[0]!.port)) throw new Error("Connected PostgreSQL server does not match the guarded S27 disposable target");
  }
  try {
    await db.query("BEGIN");
    await db.query("SELECT pg_advisory_xact_lock(61001001)");
    const existingOrg = await db.query<{ id: string }>("SELECT id FROM organizations LIMIT 1");
    const organizationId = existingOrg.rows[0]?.id ?? randomUUID();
    if (!existingOrg.rows[0]) await db.query('INSERT INTO organizations(id,name,"updatedAt") VALUES($1,$2,CURRENT_TIMESTAMP)', [organizationId, `S16 time E2E ${suffix}`]);
    const existingOwner = await db.query<{ id: string }>("SELECT id FROM accounts WHERE kind='OWNER' AND state='ACTIVE' LIMIT 1");
    ownerAccountId = existingOwner.rows[0]?.id ?? randomUUID();
    await db.query('INSERT INTO branches(id,"organizationId",name,"updatedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [branchId, organizationId, `S16 time E2E ${suffix}`]);
    await db.query('INSERT INTO teams(id,"organizationId","branchId",name,"updatedAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP)', [teamId, organizationId, branchId, `S16 time E2E ${suffix}`]);
    await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP),($3,$4,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP)', [staffAccountId, `s16-time-worker-${suffix}@example.test`, managerAccountId, `s16-time-manager-${suffix}@example.test`]);
    if (!existingOwner.rows[0]) await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'OWNER\',\'ACTIVE\',CURRENT_TIMESTAMP)', [ownerAccountId, `s16-time-owner-${suffix}@example.test`]);
    await db.query('INSERT INTO employees(id,"organizationId","accountId","homeBranchId","homeTeamId","hiredAt","updatedAt") VALUES($1,$2,$3,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP),($6,$2,$7,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP)', [managerEmployeeId, organizationId, managerAccountId, branchId, teamId, staffEmployeeId, staffAccountId]);
    await db.query('UPDATE employees SET "reportsToId"=$1 WHERE id=$2', [managerEmployeeId, staffEmployeeId]);
    await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind","branchId","teamId",reason) VALUES($1,$2,$3,\'time.manage\',\'ALLOW\',\'TEAM\',$4,$5,\'S16 time E2E scoped management\')', [randomUUID(), organizationId, managerEmployeeId, branchId, teamId]);
    const ownerKeys = await db.query<{ count: string }>('SELECT count(*)::text AS count FROM passkey_credentials WHERE "accountId"=$1 AND "revokedAt" IS NULL', [ownerAccountId]);
    for (let i = Number(ownerKeys.rows[0]?.count ?? 0); i < 2; i += 1) await db.query('INSERT INTO passkey_credentials(id,"credentialId","accountId","publicKey") VALUES($1,$2,$3,$4)', [randomUUID(), randomUUID(), ownerAccountId, randomBytes(32)]);
    const recovery = await db.query('SELECT id FROM owner_recovery_codes WHERE "accountId"=$1 AND "usedAt" IS NULL AND "replacedAt" IS NULL AND "acknowledgedAt" IS NOT NULL LIMIT 1', [ownerAccountId]);
    if (!recovery.rowCount) await db.query('INSERT INTO owner_recovery_codes(id,"accountId","codeHash","acknowledgedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [randomUUID(), ownerAccountId, digest(randomUUID())]);
    await db.query('INSERT INTO sessions(id,"accountId","tokenHash","csrfTokenHash","expiresAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP+interval \'2 hours\'),($5,$6,$7,$8,CURRENT_TIMESTAMP+interval \'2 hours\'),($9,$10,$11,$12,CURRENT_TIMESTAMP+interval \'2 hours\')', [staffSessionId, staffAccountId, digest(staffSecret), digest(staffCsrf), managerSessionId, managerAccountId, digest(managerSecret), digest(managerCsrf), ownerSessionId, ownerAccountId, digest(ownerSecret), digest(ownerCsrf)]);
    await db.query("COMMIT");

    await context.addCookies([{ name: "sense_sid", value: staffSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/time");
    const workspace = page.locator(".time-workspace");
    await expect(workspace.getByRole("heading", { name: "Time", exact: true })).toBeVisible();
    const timerPanel = workspace.locator(".time-panel").first();
    await expect(timerPanel.getByRole("heading", { name: "Start a timer" })).toBeVisible();
    await timerPanel.getByLabel("Activity label").fill("Studio administration");
    await timerPanel.getByLabel("Work note").fill(timerNote);
    await timerPanel.getByRole("button", { name: "Start timer" }).click();
    await expect(timerPanel.getByRole("heading", { name: "Active timer" })).toBeVisible();
    await timerPanel.getByRole("button", { name: "Pause" }).click();
    await expect(timerPanel.getByText(new RegExp(`${timerNote} · paused`))).toBeVisible();
    await timerPanel.getByRole("button", { name: "Resume" }).click();
    await expect(timerPanel.getByText(new RegExp(`${timerNote} · running`))).toBeVisible();
    page.once("dialog", (dialog) => dialog.accept("Timer journey complete"));
    await timerPanel.getByRole("button", { name: "Stop timer" }).click();
    await expect(timerPanel.getByRole("heading", { name: "Start a timer" })).toBeVisible();
    const timerRow = await db.query<{ id: string; timerId: string; state: string; version: number; durationSeconds: number }>(`SELECT e.id,e."timerId",t.state::text,t.version,(v.data->>'durationSeconds')::int AS "durationSeconds" FROM time_entries e JOIN time_timers t ON t.id=e."timerId" JOIN time_entry_versions v ON v."entryId"=e.id AND v.version=1 WHERE e."employeeId"=$1 AND v.data->>'workNote'=$2`, [staffEmployeeId, timerNote]);
    expect(timerRow.rows).toHaveLength(1);
    expect(timerRow.rows[0]).toMatchObject({ state: "STOPPED", version: 4 });

    const manualPanel = workspace.locator(".time-panel").filter({ has: page.getByRole("heading", { name: "Log time manually" }) });
    await manualPanel.getByLabel("Activity label").fill("Planning");
    await manualPanel.getByLabel("Date").fill("2026-10-01");
    await manualPanel.getByLabel("Duration (seconds)").fill("2700");
    await manualPanel.getByLabel("Work location").selectOption("REMOTE");
    await manualPanel.getByLabel("Billable").uncheck();
    await manualPanel.getByLabel("Work note").fill(manualNote);
    await manualPanel.getByRole("button", { name: "Save time entry" }).click();
    await expect(workspace.getByText("Time record updated.")).toBeVisible();
    const manualRow = await db.query<{ id: string; version: number }>(`SELECT e.id,e.version FROM time_entries e JOIN time_entry_versions v ON v."entryId"=e.id AND v.version=1 WHERE e."employeeId"=$1 AND v.data->>'workNote'=$2`, [staffEmployeeId, manualNote]);
    expect(manualRow.rows).toHaveLength(1);
    const manualEntryId = manualRow.rows[0]!.id;
    const persisted = await db.query<{ durationSeconds: number; location: string; billable: boolean }>(`SELECT (data->>'durationSeconds')::int AS "durationSeconds",data->>'location' AS location,(data->>'billable')::boolean AS billable FROM time_entry_versions WHERE "entryId"=$1 AND version=1`, [manualEntryId]);
    expect(persisted.rows[0]).toEqual({ durationSeconds: 2700, location: "REMOTE", billable: false });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("s16-time-worker-timer-manual.png"), fullPage: true });

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: managerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/time");
    await expect(workspace.getByRole("heading", { name: "Time", exact: true })).toBeVisible();
    await workspace.locator(".time-toolbar").getByLabel("View").selectOption("managed");
    const managerEntry = workspace.locator(".time-entry").filter({ hasText: manualNote });
    await expect(managerEntry).toBeVisible();
    page.once("dialog", (dialog) => dialog.accept("Approve the original entry before its locked correction"));
    await managerEntry.getByRole("button", { name: "Approve" }).click();
    await expect(managerEntry.getByText("Approved")).toBeVisible();
    await managerEntry.getByRole("button", { name: "Correct" }).click();
    const correction = page.getByRole("dialog", { name: "Correct time entry" });
    await correction.getByLabel("Work note").fill(correctedNote);
    await correction.getByLabel("Duration (seconds)").fill("3000");
    await correction.getByLabel("Reason for correction").fill("Clarify the recorded non-project duration");
    await correction.getByRole("button", { name: "Save correction" }).click();
    await expect(workspace.getByText("Time record updated.")).toBeVisible();
    const corrected = await db.query<{ version: number; approvedVersion: number | null; locked: boolean }>('SELECT version,"approvedVersion",locked FROM time_entries WHERE id=$1', [manualEntryId]);
    expect(corrected.rows[0]).toEqual({ version: 2, approvedVersion: null, locked: true });
    const correctedEntry = workspace.locator(".time-entry").filter({ hasText: correctedNote });
    await expect(correctedEntry.getByText("Pending approval")).toBeVisible();
    page.once("dialog", (dialog) => dialog.accept("Approve the corrected version"));
    await correctedEntry.getByRole("button", { name: "Approve" }).click();
    await expect(correctedEntry.getByText("Approved")).toBeVisible();
    const approval = await db.query<{ approvedVersion: number | null }>('SELECT "approvedVersion" FROM time_entries WHERE id=$1', [manualEntryId]);
    expect(approval.rows[0]?.approvedVersion).toBe(2);

    const receiverHeaders = { "x-s16-test-token": receiverToken! };
    const stateBefore = await (await fetch(`${receiverUrl!.replace(/\/$/, "")}/__test/state`, { headers: receiverHeaders })).json() as { records: Array<{ recordId: string }>; deliveries: Array<{ recordId: string }> };
    expect(stateBefore.records.some((record) => record.recordId === manualEntryId)).toBe(false);
    const armed = await fetch(`${receiverUrl!.replace(/\/$/, "")}/__test/failure`, { method: "POST", headers: { ...receiverHeaders, "Content-Type": "application/json" }, body: JSON.stringify({ recordId: manualEntryId, mode: "ACCEPT_THEN_LOSE_ACK" }) });
    expect(armed.status).toBe(204);
    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: ownerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/time");
    await expect(workspace.getByRole("heading", { name: "Time", exact: true })).toBeVisible();
    await workspace.locator(".time-toolbar").getByLabel("View").selectOption("managed");
    const ownerEntry = workspace.locator(".time-entry").filter({ hasText: correctedNote });
    page.once("dialog", (dialog) => dialog.accept("Export approved version to accounting"));
    const exportResponsePromise = page.waitForResponse((response) => response.url().endsWith(`/api/v1/time/entries/${manualEntryId}/export`));
    await ownerEntry.getByRole("button", { name: "Export" }).click();
    expect((await exportResponsePromise).status()).toBe(201);
    await ownerEntry.getByText("Accounting delivery").click();
    await expect(ownerEntry.getByText(/FAILED · revision 2 · 1 attempts/)).toBeVisible();
    const deliveryRow = await db.query<{ id: string }>(`SELECT id FROM time_accounting_deliveries WHERE "entryId"=$1 AND revision=2`, [manualEntryId]);
    expect(deliveryRow.rows).toHaveLength(1);
    page.once("dialog", (dialog) => dialog.accept("Retry the delivery after the receiver accepted it"));
    const retryResponsePromise = page.waitForResponse((response) => response.url().endsWith(`/api/v1/time/deliveries/${deliveryRow.rows[0]!.id}/retry`));
    await ownerEntry.getByRole("button", { name: "Retry" }).click();
    expect((await retryResponsePromise).status()).toBe(201);
    await expect(ownerEntry.getByText(/DELIVERED · revision 2 · 2 attempts/)).toBeVisible();
    const finalState = await (await fetch(`${receiverUrl!.replace(/\/$/, "")}/__test/state`, { headers: receiverHeaders })).json() as { acceptedRecordCount: number; deliveryCount: number; records: Array<{ recordId: string; revision: number; payloadHash: string; payload: { workNote: string } }>; revisions: Array<{ recordId: string; revision: number }> ; deliveries: Array<{ recordId: string; revision: number; payloadHash: string }> };
    expect(finalState.records.filter((record) => record.recordId === manualEntryId)).toEqual([expect.objectContaining({ recordId: manualEntryId, revision: 2, payload: expect.objectContaining({ workNote: correctedNote }) })]);
    expect(finalState.revisions.filter((revision) => revision.recordId === manualEntryId)).toHaveLength(1);
    expect(finalState.deliveries.filter((delivery) => delivery.recordId === manualEntryId)).toHaveLength(1);
    const delivery = await db.query<{ state: string; revision: number; attempts: number; payloadHash: string }>(`SELECT state,revision,attempts,"payloadHash" FROM time_accounting_deliveries WHERE "entryId"=$1`, [manualEntryId]);
    expect(delivery.rows[0]).toMatchObject({ state: "DELIVERED", revision: 2, attempts: 2 });
    expect(delivery.rows[0]?.payloadHash).toMatch(/^[0-9a-f]{64}$/);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("s16-time-owner-export-retry.png"), fullPage: true });

    await page.reload();
    await workspace.locator(".time-toolbar").getByLabel("View").selectOption("managed");
    const reloadedOwnerEntry = workspace.locator(".time-entry").filter({ hasText: correctedNote });
    await reloadedOwnerEntry.getByText("Accounting delivery").click();
    await expect(reloadedOwnerEntry.getByText("DELIVERED · revision 2 · 2 attempts")).toBeVisible();
  } finally {
    await db.query("ROLLBACK").catch(() => undefined);
    await db.end();
  }
});
