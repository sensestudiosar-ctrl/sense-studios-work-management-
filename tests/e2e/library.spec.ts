import { test, expect } from "@playwright/test";
import { createHash, createHmac, randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { s18ScreenshotPath } from "./s18-screenshot.js";

const databaseUrl = process.env.DATABASE_URL;
const suffix = randomUUID();
const digest = (value: string) => createHash("sha256").update(value).digest("hex");
type PgClient = {
  connect(): Promise<void>;
  query<T = Record<string, unknown>>(sql: string, values?: unknown[]): Promise<{ rows: T[]; rowCount: number | null }>;
  end(): Promise<void>;
};

test("Owner publishes private Library file history and staff acknowledges exact versions", async ({ page, context, baseURL }, testInfo) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(10_000);
  if (!databaseUrl) throw new Error("DATABASE_URL must point to the same dedicated local test database used by the API; Library browser acceptance never skips silently");
  const parsed = new URL(databaseUrl);
  if (!["localhost", "127.0.0.1"].includes(parsed.hostname) || parsed.port !== "57433" || !/^[a-z0-9_]+_test$/.test(parsed.pathname.slice(1))) throw new Error("Library browser acceptance requires a dedicated local PostgreSQL _test database on port 57433");
  const require = createRequire(resolve("apps/api/package.json"));
  const { Client } = require("pg") as { Client: new (options: { connectionString: string }) => PgClient };
  const db = new Client({ connectionString: databaseUrl });
  const ownerSecret = randomBytes(32).toString("base64url"), managerSecret = randomBytes(32).toString("base64url"), employeeSecret = randomBytes(32).toString("base64url");
  const ownerCsrf = createHmac("sha256", ownerSecret).update("csrf").digest("base64url"), managerCsrf = createHmac("sha256", managerSecret).update("csrf").digest("base64url"), employeeCsrf = createHmac("sha256", employeeSecret).update("csrf").digest("base64url");
  const ownerSessionId = randomUUID(), managerSessionId = randomUUID(), employeeSessionId = randomUUID(), branchId = randomUUID(), teamId = randomUUID(), managerId = randomUUID(), employeeId = randomUUID(), managerAccountId = randomUUID(), employeeAccountId = randomUUID();
  let ownerAccountId: string, organizationId: string, recordId: string, version2Id: string, fileId: string, knowledgeRecordId: string, approvalRequestId: string;
  const title = `Library acceptance ${suffix.slice(0, 8)}`;
  const pdfBytes = Buffer.from("%PDF-1.7\nPrivate Library acceptance document\n%%EOF\n");
  await db.connect();
  try {
    await db.query("BEGIN");
    await db.query("SELECT pg_advisory_xact_lock(61001805)");
    const org = await db.query<{ id: string }>("SELECT id FROM organizations LIMIT 1");
    organizationId = org.rows[0]?.id ?? randomUUID();
    if (!org.rows[0]) await db.query('INSERT INTO organizations(id,name,"updatedAt") VALUES($1,$2,CURRENT_TIMESTAMP)', [organizationId, `S18 Library ${suffix}`]);
    const owner = await db.query<{ id: string }>("SELECT id FROM accounts WHERE kind='OWNER' AND state='ACTIVE' LIMIT 1");
    ownerAccountId = owner.rows[0]?.id ?? randomUUID();
    if (!owner.rows[0]) await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'OWNER\',\'ACTIVE\',CURRENT_TIMESTAMP)', [ownerAccountId, `s18-library-owner-${suffix}@example.test`]);
    await db.query('INSERT INTO branches(id,"organizationId",name,"updatedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [branchId, organizationId, `Library branch ${suffix}`]);
    await db.query('INSERT INTO teams(id,"organizationId","branchId",name,"updatedAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP)', [teamId, organizationId, branchId, `Library team ${suffix}`]);
    await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP),($3,$4,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP)', [managerAccountId, `s18-library-manager-${suffix}@example.test`, employeeAccountId, `s18-library-employee-${suffix}@example.test`]);
    await db.query('INSERT INTO employees(id,"organizationId","accountId","homeBranchId","homeTeamId","hiredAt","updatedAt") VALUES($1,$2,$3,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP),($6,$2,$7,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP)', [managerId, organizationId, managerAccountId, branchId, teamId, employeeId, employeeAccountId]);
    await db.query('UPDATE employees SET "reportsToId"=$1 WHERE id=$2', [managerId, employeeId]);
    await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind",reason) VALUES($1,$2,$3,\'library.view\',\'ALLOW\',\'ORGANIZATION\',$4)', [randomUUID(), organizationId, employeeId, "Explicit organization Library read access for browser acceptance"]);
    await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind","branchId","teamId",reason) VALUES($1,$2,$3,\'library.view\',\'ALLOW\',\'TEAM\',$4,$5,$6),($7,$2,$3,\'library.manage\',\'ALLOW\',\'TEAM\',$4,$5,$8)', [randomUUID(), organizationId, managerId, branchId, teamId, "Scoped Library view for independent publication", randomUUID(), "Scoped Library publisher authority"]);
    await db.query('INSERT INTO sessions(id,"accountId","tokenHash","csrfTokenHash","expiresAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP+interval \'2 hours\'),($5,$6,$7,$8,CURRENT_TIMESTAMP+interval \'2 hours\'),($9,$10,$11,$12,CURRENT_TIMESTAMP+interval \'2 hours\')', [ownerSessionId, ownerAccountId, digest(ownerSecret), digest(ownerCsrf), managerSessionId, managerAccountId, digest(managerSecret), digest(managerCsrf), employeeSessionId, employeeAccountId, digest(employeeSecret), digest(employeeCsrf)]);
    const keyCount = await db.query<{ count: string }>('SELECT count(*)::text AS count FROM passkey_credentials WHERE "accountId"=$1 AND "revokedAt" IS NULL', [ownerAccountId]);
    for (let i = Number(keyCount.rows[0]?.count ?? 0); i < 2; i += 1) await db.query('INSERT INTO passkey_credentials(id,"credentialId","accountId","publicKey") VALUES($1,$2,$3,$4)', [randomUUID(), randomUUID(), ownerAccountId, randomBytes(32)]);
    const recovery = await db.query('SELECT id FROM owner_recovery_codes WHERE "accountId"=$1 AND "usedAt" IS NULL AND "replacedAt" IS NULL AND "acknowledgedAt" IS NOT NULL LIMIT 1', [ownerAccountId]);
    if (!recovery.rowCount) await db.query('INSERT INTO owner_recovery_codes(id,"accountId","codeHash","acknowledgedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [randomUUID(), ownerAccountId, digest(randomUUID())]);
    await db.query("COMMIT");

    await context.addCookies([{ name: "sense_sid", value: ownerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    const workspace = page.locator(".learning-route");
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await expect(workspace.getByRole("heading", { name: "Library", exact: true })).toBeVisible();
    await workspace.getByRole("button", { name: "Create record" }).click();
    const form = workspace.locator("form.library-form").first();
    await form.getByLabel("Type").selectOption("SOP");
    await form.getByLabel("Title").fill(title);
    await form.getByLabel("Category").selectOption("Company policy");
    await form.getByLabel("Text").fill("Read the current site safety standard.");
    await form.getByLabel("Require acknowledgement for this version").check();
    await form.getByLabel("Reason").fill("Create the approved site safety SOP");
    const createResponse = page.waitForResponse(response => response.url().endsWith("/api/v1/library") && response.request().method() === "POST");
    await form.getByRole("button", { name: "Create draft" }).click();
    const created = await createResponse;
    expect(created.ok(), await created.text()).toBe(true);
    recordId = (await created.json() as { record: { id: string } }).record.id;
    await expect(workspace.getByRole("heading", { name: title })).toBeVisible();
    const publication = workspace.locator(".library-panel").filter({ has: page.getByRole("heading", { name: "Publication and activation", exact: true }) });
    await publication.getByLabel("Owner publication reason").fill("Owner directly approves this current SOP version");
    const publishResponse = page.waitForResponse(response => response.url().endsWith(`/api/v1/library/${recordId}/publish`) && response.request().method() === "POST");
    await publication.getByRole("button", { name: "Publish current version" }).click();
    const published = await publishResponse;
    expect(published.ok(), await published.text()).toBe(true);
    await expect(workspace.getByText("Version published by Owner.")).toBeVisible();
    const version1 = await db.query<{ id: string; version: number; acknowledgementRequired: boolean }>('SELECT id,version,"acknowledgementRequired" FROM library_versions WHERE "recordId"=$1 AND version=1', [recordId]);
    expect(version1.rows).toEqual([{ id: expect.any(String), version: 1, acknowledgementRequired: true }]);

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: employeeSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await workspace.getByRole("button", { name: new RegExp(title) }).click();
    await expect(workspace.getByRole("button", { name: "Acknowledge version 1" })).toBeVisible();
    await workspace.getByRole("button", { name: "Acknowledge version 1" }).click();
    await expect(workspace.getByText("Acknowledgement recorded for this exact version.")).toBeVisible();
    expect((await db.query('SELECT id FROM library_acknowledgements WHERE "employeeId"=$1 AND "versionId"=$2', [employeeId, version1.rows[0]!.id])).rowCount).toBe(1);

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: ownerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await workspace.getByRole("button", { name: new RegExp(title) }).click();
    const versionForm = workspace.locator("form.library-version-form");
    await versionForm.getByLabel("Text").fill("Read the current site safety standard and attached guide.");
    await versionForm.getByRole("button", { name: "Add file block" }).click();
    const file = await workspace.getByLabel("Upload private file");
    await file.setInputFiles({ name: "safety-guide.pdf", mimeType: "application/pdf", buffer: pdfBytes });
    await expect(workspace.getByText("File uploaded privately. Save the version to attach it to this content.")).toBeVisible();
    await versionForm.getByLabel("Require acknowledgement").check();
    await versionForm.getByLabel("Reason").fill("Attach the reviewed PDF guide");
    const appendResponse = page.waitForResponse(response => response.url().endsWith(`/api/v1/library/${recordId}/versions`) && response.request().method() === "POST");
    await versionForm.getByRole("button", { name: "Save version" }).click();
    const appended = await appendResponse;
    expect(appended.ok(), await appended.text()).toBe(true);
    version2Id = (await appended.json() as { versionId: string }).versionId;
    await expect(workspace.getByText("New version saved.")).toBeVisible();
    await expect(workspace.locator(".library-workspace")).toHaveAttribute("aria-busy", "false");
    await expect(versionForm.getByLabel("Reason")).toHaveValue("");
    const fileRow = await db.query<{ id: string; name: string; mime: string; bytes: number; checksum: string; storageKey: string }>('SELECT id,name,mime,bytes::int AS bytes,checksum,"storageKey" FROM library_files WHERE "recordId"=$1', [recordId]);
    fileId = fileRow.rows[0]!.id;
    expect(fileRow.rows).toEqual([{ id: fileId, name: "safety-guide.pdf", mime: "application/pdf", bytes: pdfBytes.length, checksum: digest(pdfBytes.toString()), storageKey: expect.any(String) }]);
    expect(fileRow.rows[0]!.storageKey).toBe(fileId);
    await publication.getByLabel("Owner publication reason").fill("Owner approves the reviewed guide version");
    await expect(publication.getByRole("button", { name: "Publish current version" })).toBeEnabled();
    const publishSecond = page.waitForResponse(response => response.url().endsWith(`/api/v1/library/${recordId}/publish`) && response.request().method() === "POST");
    await publication.getByRole("button", { name: "Publish current version" }).click();
    const secondPublication = await publishSecond;
    expect(secondPublication.ok(), await secondPublication.text()).toBe(true);
    expect((await db.query('SELECT id FROM library_publications WHERE "recordId"=$1', [recordId])).rowCount).toBe(2);

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: employeeSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await workspace.getByRole("button", { name: new RegExp(title) }).click();
    await expect(workspace.getByText("Read the current site safety standard and attached guide.")).toBeVisible();
    await expect(workspace.getByText("Read the current site safety standard.")).toBeVisible();
    await expect(workspace.getByRole("link", { name: /safety-guide\.pdf.*Open private file/ })).toBeVisible();
    await expect(workspace.getByRole("button", { name: "Acknowledge version 2" })).toBeVisible();
    await workspace.getByRole("button", { name: "Acknowledge version 2" }).click();
    await expect(workspace.getByText("Acknowledgement recorded for this exact version.")).toBeVisible();
    expect((await db.query('SELECT count(*)::int AS count FROM library_acknowledgements WHERE "employeeId"=$1 AND "versionId" IN ($2,$3)', [employeeId, version1.rows[0]!.id, version2Id])).rows[0]?.count).toBe(2);

    await workspace.getByRole("button", { name: "Create record" }).click();
    const employeeForm = workspace.locator("form.library-form").first();
    await employeeForm.getByLabel("Type").selectOption("KNOWLEDGE");
    const teamAudience = await employeeForm.getByLabel("Audience").locator("option").filter({ hasText: "TEAM" }).getAttribute("value");
    expect(teamAudience).toBeTruthy();
    await employeeForm.getByLabel("Audience").selectOption(teamAudience!);
    const knowledgeTitle = `Employee knowledge ${suffix.slice(0, 8)}`;
    await employeeForm.getByLabel("Title").fill(knowledgeTitle);
    await employeeForm.getByLabel("Category").selectOption("Lessons learned");
    await employeeForm.getByLabel("Text").fill("Check the wall condition before selecting the fixing.");
    await employeeForm.getByLabel("Reason").fill("Share a field lesson with my team");
    const knowledgeCreate = page.waitForResponse(response => response.url().endsWith("/api/v1/library") && response.request().method() === "POST");
    await employeeForm.getByRole("button", { name: "Create draft" }).click();
    const knowledgeCreated = await knowledgeCreate;
    expect(knowledgeCreated.ok(), await knowledgeCreated.text()).toBe(true);
    knowledgeRecordId = (await knowledgeCreated.json() as { record: { id: string } }).record.id;
    await expect(workspace.getByRole("heading", { name: knowledgeTitle })).toBeVisible();
    const reviewPanel = workspace.locator(".library-panel").filter({ has: page.getByRole("heading", { name: "Publication and activation", exact: true }) });
    const publisher = reviewPanel.getByLabel("Eligible publisher");
    const managerOption = publisher.locator(`option[value="${managerAccountId}"]`);
    await expect(managerOption).toContainText(`s18-library-manager-${suffix}@example.test`);
    await publisher.selectOption(managerAccountId);
    await reviewPanel.getByLabel("Reason").fill("Submit this field lesson for independent review");
    const requestPublish = page.waitForResponse(response => response.url().endsWith(`/api/v1/library/${knowledgeRecordId}/publication-requests`) && response.request().method() === "POST");
    await reviewPanel.getByRole("button", { name: /Request publication of version/ }).click();
    const requestResult = await requestPublish;
    expect(requestResult.ok(), await requestResult.text()).toBe(true);
    approvalRequestId = (await requestResult.json() as { approvalRequestId: string }).approvalRequestId;

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: managerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await workspace.getByRole("button", { name: new RegExp(knowledgeTitle) }).click();
    const pendingRequest = workspace.locator(".library-request").filter({ hasText: "PENDING" });
    await expect(pendingRequest.getByRole("button", { name: "Approve and publish" })).toBeVisible();
    await pendingRequest.getByLabel("Decision reason").fill("Independent review confirms the field lesson is useful");
    const decisionResponse = page.waitForResponse(response => response.url().endsWith(`/api/v1/library/publication-requests/${approvalRequestId}/decision`) && response.request().method() === "POST");
    await pendingRequest.getByRole("button", { name: "Approve and publish" }).click();
    const decision = await decisionResponse;
    expect(decision.ok(), await decision.text()).toBe(true);
    expect((await db.query<{ state: string; requesterId: string; approverId: string }>('SELECT state::text,"requesterId","approverId" FROM approval_requests WHERE id=$1', [approvalRequestId])).rows).toEqual([{ state: "APPROVED", requesterId: employeeAccountId, approverId: managerAccountId }]);

    await context.clearCookies();
    await context.addCookies([{ name: "sense_sid", value: employeeSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/learning");
    await workspace.getByRole("button", { name: "Library", exact: true }).click();
    await workspace.getByRole("button", { name: new RegExp(knowledgeTitle) }).click();
    await expect(workspace.getByText("Check the wall condition before selecting the fixing.")).toBeVisible();
    await expect(workspace.getByText(/APPROVED/)).toBeVisible();
    expect((await db.query('SELECT id FROM library_publications WHERE "recordId"=$1 AND "versionId"=(SELECT id FROM library_versions WHERE "recordId"=$1 AND version=1)', [knowledgeRecordId])).rowCount).toBe(1);
    const overflow = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: window.innerWidth }));
    expect(overflow.scroll).toBeLessThanOrEqual(overflow.width);
    await page.screenshot({ path: await s18ScreenshotPath(`library-${testInfo.project.name}.png`), fullPage: true });
  } finally {
    await db.end();
  }
});
