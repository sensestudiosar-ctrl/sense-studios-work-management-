import { test, expect } from "@playwright/test";
import { createHash, createHmac, randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";

test("Owner provisions project folders and grants confidential PDF access; assigned staff uploads, refreshes and downloads", async ({ page, context, baseURL }) => {
  test.setTimeout(90_000);
  test.skip(!process.env.DATABASE_URL || !process.env.NAS_ROOT, "Dedicated local test database and isolated NAS_ROOT are required");
  const url = new URL(process.env.DATABASE_URL!);
  if (!["localhost", "127.0.0.1", "db"].includes(url.hostname) || !url.pathname.endsWith("_test")) throw new Error("Document browser fixture requires a dedicated test database");
  const require = createRequire(resolve("apps/api/package.json"));
  const { Client } = require("pg") as typeof import("pg");
  const db = new Client({ connectionString: process.env.DATABASE_URL });
  const suffix = randomUUID();
  const ownerSecret = randomBytes(32).toString("base64url"), staffSecret = randomBytes(32).toString("base64url");
  const csrf = (secret: string) => createHmac("sha256", secret).update("csrf").digest("base64url");
  const hash = (value: string) => createHash("sha256").update(value).digest("hex");
  const organizationId = randomUUID(), branchId = randomUUID(), teamId = randomUUID();
  const staffId = randomUUID(), employeeId = randomUUID(), projectId = randomUUID();
  const ownerSessionId = randomUUID(), staffSessionId = randomUUID();
  const title = `S11 document ${suffix.slice(0, 8)}`;
  await db.connect();
  let ownerAccountId = "";
  let committed = false;
  try {
    await db.query("BEGIN");
    await db.query("SELECT pg_advisory_xact_lock(6092706)");
    const org = await db.query<{ id: string }>("SELECT id FROM organizations LIMIT 1");
    const orgId = org.rows[0]?.id ?? organizationId;
    if (!org.rows[0]) await db.query('INSERT INTO organizations(id,name,"updatedAt") VALUES($1,$2,CURRENT_TIMESTAMP)', [orgId, "S11 document browser fixture"]);
    const owner = await db.query<{ id: string }>("SELECT id FROM accounts WHERE kind='OWNER' AND state='ACTIVE' LIMIT 1");
    ownerAccountId = owner.rows[0]?.id ?? randomUUID();
    if (!owner.rows[0]) {
      await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'OWNER\',\'ACTIVE\',CURRENT_TIMESTAMP)', [ownerAccountId, `s11-doc-owner-${suffix}@example.test`]);
      await db.query('INSERT INTO passkey_credentials(id,"credentialId","accountId","publicKey") VALUES($1,$2,$3,$4),($5,$6,$3,$7)', [randomUUID(), randomUUID(), ownerAccountId, randomBytes(32), randomUUID(), randomUUID(), randomBytes(32)]);
      await db.query('INSERT INTO owner_recovery_codes(id,"accountId","codeHash","acknowledgedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [randomUUID(), ownerAccountId, hash(randomUUID())]);
    }
    await db.query('INSERT INTO branches(id,"organizationId",name,"updatedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [branchId, orgId, `S11 document ${suffix}`]);
    await db.query('INSERT INTO teams(id,"organizationId","branchId",name,"updatedAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP)', [teamId, orgId, branchId, `S11 docs team ${suffix}`]);
    await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP)', [staffId, `s11-doc-staff-${suffix}@example.test`]);
    await db.query('INSERT INTO employees(id,"organizationId","accountId","homeBranchId","homeTeamId","hiredAt","updatedAt") VALUES($1,$2,$3,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP)', [employeeId, orgId, staffId, branchId, teamId]);
    for (const permissionKey of ["project.view", "document.view", "document.upload"]) await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind","branchId",reason) VALUES($1,$2,$3,$4,\'ALLOW\',\'BRANCH\',$5,$6)', [randomUUID(), orgId, employeeId, permissionKey, branchId, "S11 browser fixture"]);
    await db.query('INSERT INTO projects(id,"organizationId","branchId",title,"deliveryType","createdById","updatedAt") VALUES($1,$2,$3,$4,\'DESIGN\',$5,CURRENT_TIMESTAMP)', [projectId, orgId, branchId, title, ownerAccountId]);
    await db.query('INSERT INTO project_scopes(id,"projectId","organizationId",name,"normalizedName",baseline) VALUES($1,$2,$3,$4,$5,true)', [randomUUID(), projectId, orgId, "Architecture", "architecture"]);
    await db.query('INSERT INTO project_status_changes(id,"projectId","organizationId","toStatus","projectVersion","actorId",reason) VALUES($1,$2,$3,\'DRAFT\',1,$4,$5)', [randomUUID(), projectId, orgId, ownerAccountId, "S11 browser fixture"]);
    await db.query('INSERT INTO project_assignments(id,"projectId","organizationId","employeeId","grantedById","grantReason") VALUES($1,$2,$3,$4,$5,$6)', [randomUUID(), projectId, orgId, employeeId, ownerAccountId, "S11 document assignment"]);
    const templateId = randomUUID(), templateVersionId = randomUUID();
    const definition = { deliveryType: "DESIGN", scopes: ["Architecture"], stages: [{ key: "DESIGN", label: "Design" }], milestones: [], folders: ["Drawings/Issued"] };
    await db.query('INSERT INTO project_templates(id,"organizationId",name,"createdById") VALUES($1,$2,$3,$4)', [templateId, orgId, `S11 template ${suffix}`, ownerAccountId]);
    await db.query('INSERT INTO project_template_versions(id,"organizationId","templateId",number,definition,"createdById",reason) VALUES($1,$2,$3,1,$4::jsonb,$5,$6)', [templateVersionId, orgId, templateId, JSON.stringify(definition), ownerAccountId, "S11 folder intent"]);
    await db.query('INSERT INTO project_plans(id,"organizationId","projectId","templateVersionId",definition) VALUES($1,$2,$3,$4,$5::jsonb)', [randomUUID(), orgId, projectId, templateVersionId, JSON.stringify(definition)]);
    await db.query('INSERT INTO project_plan_items(id,"organizationId","projectId",kind,key,label,position) VALUES($1,$2,$3,\'STAGE\',\'DESIGN\',\'Design\',0)', [randomUUID(), orgId, projectId]);
    await db.query('INSERT INTO sessions(id,"accountId","tokenHash","csrfTokenHash","expiresAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP+interval \'1 hour\'),($5,$6,$7,$8,CURRENT_TIMESTAMP+interval \'1 hour\')', [ownerSessionId, ownerAccountId, hash(ownerSecret), hash(csrf(ownerSecret)), staffSessionId, staffId, hash(staffSecret), hash(csrf(staffSecret))]);
    await db.query("COMMIT");
    committed = true;

    const useSession = async (secret: string) => context.addCookies([{ name: "sense_sid", value: secret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await useSession(ownerSecret);
    await page.goto("/documents");
    const workspace = page.locator(".document-workspace");
    await expect(workspace.getByRole("heading", { name: "Documents" })).toBeVisible();
    await expect(workspace.getByLabel("Document project branch").locator(`option[value="${branchId}"]`)).toHaveCount(1);
    await expect(workspace.getByText("Loading project document access…")).toBeHidden();
    const chooseProject = async () => {
      await workspace.getByLabel("Document project branch").selectOption({ index: 0 });
      await expect(workspace.getByText("Loading project document access…")).toBeHidden();
      await workspace.getByLabel("Document project branch").selectOption(branchId);
      await expect(workspace.getByLabel("Document project", { exact: true }).locator(`option[value="${projectId}"]`)).toHaveCount(1);
      await workspace.getByLabel("Document project", { exact: true }).selectOption(projectId);
      await expect(workspace.getByLabel("Document project", { exact: true })).toHaveValue(projectId);
    };
    await chooseProject();
    await expect(workspace.getByText("No files have been registered for this project.")).toBeVisible();
    await workspace.getByRole("button", { name: "Set up template folders" }).click();
    await expect(workspace.getByRole("status").filter({ hasText: "Applied template folders are set up" })).toBeVisible();
    await expect(workspace.getByLabel("Upload destination folder").locator("option", { hasText: "Issued" })).toHaveCount(1);
    const templateFolders = await db.query<{ count: string }>('SELECT count(*)::text AS count FROM document_folders WHERE "projectId"=$1 AND "templatePath" IS NOT NULL AND "provisionState"=\'READY\'', [projectId]);
    expect(templateFolders.rows[0]?.count).toBe("2");

    await workspace.getByLabel("Folder name").fill("Confidential");
    await workspace.getByLabel("Confidential folder").check();
    await workspace.getByLabel("Reason").first().fill("Create restricted project area");
    await workspace.getByRole("button", { name: "Create folder" }).click();
    await expect(workspace.getByText("Folder created.")).toBeVisible();
    const privateFolder = await db.query<{ id: string }>('SELECT id FROM document_folders WHERE "projectId"=$1 AND name=\'Confidential\'', [projectId]);
    expect(privateFolder.rows).toHaveLength(1);

    const bytes = Buffer.from("%PDF-1.7\nS11 browser fixture PDF\n%%EOF\n", "ascii");
    await workspace.getByLabel("Upload destination folder").selectOption(privateFolder.rows[0]!.id);
    await workspace.getByLabel("File", { exact: true }).setInputFiles({ name: "confidential.pdf", mimeType: "application/pdf", buffer: bytes });
    await workspace.getByLabel("Confidential file").check();
    await workspace.getByLabel("Mark as view only").check();
    await workspace.getByLabel("Reason").nth(1).fill("Register restricted issued drawing");
    await workspace.getByRole("button", { name: "Upload and register" }).click();
    await expect(workspace.getByText("File uploaded and registered.")).toBeVisible();
    const document = await db.query<{ id: string; sha256: string; storageKey: string }>('SELECT d.id,b."sha256",b."storageKey" FROM documents d JOIN file_blob_metadata b ON b."documentId"=d.id WHERE d."projectId"=$1 AND b."fileName"=\'confidential.pdf\'', [projectId]);
    expect(document.rows).toHaveLength(1);
    expect(document.rows[0]?.sha256).toBe(createHash("sha256").update(bytes).digest("hex"));
    expect(document.rows[0]?.storageKey).not.toContain("\\");
    await page.reload();
    await expect(workspace.getByLabel("Document project branch").locator(`option[value="${branchId}"]`)).toHaveCount(1);
    await expect(workspace.getByText("Loading project document access…")).toBeHidden();
    await chooseProject();
    await expect(workspace.getByText("confidential.pdf")).toBeVisible();

    const staffHeaders = { Cookie: `sense_sid=${staffSecret}` };
    expect((await page.request.get(`/api/v1/documents/files/${document.rows[0]!.id}/stream`, { headers: staffHeaders })).status()).toBe(403);
    await workspace.getByLabel("Resource type").selectOption("FOLDER");
    await workspace.getByLabel("Folder or file").selectOption(privateFolder.rows[0]!.id);
    await workspace.getByLabel("Project employee").selectOption(employeeId);
    await workspace.getByLabel("Reason").last().fill("Allow assigned staff to access restricted folder");
    await workspace.getByRole("button", { name: "Grant access" }).click();
    await expect(workspace.getByText("Confidential access granted.")).toBeVisible();
    await workspace.getByLabel("Resource type").selectOption("FILE");
    await workspace.getByLabel("Folder or file").selectOption(document.rows[0]!.id);
    await workspace.getByLabel("Project employee").selectOption(employeeId);
    await workspace.getByLabel("Reason").last().fill("Allow assigned staff to access this restricted file");
    await workspace.getByRole("button", { name: "Grant access" }).click();
    await expect(workspace.getByText("Confidential access granted.")).toBeVisible();
    // Switch the browser identity before repeating the stream authorization check.
    await useSession(staffSecret);
    expect((await page.request.get(`/api/v1/documents/files/${document.rows[0]!.id}/stream`)).status()).toBe(200);
    await page.reload();
    await expect(workspace.getByLabel("Document project branch").locator(`option[value="${branchId}"]`)).toHaveCount(1);
    await expect(workspace.getByText("Loading project document access…")).toBeHidden();
    await chooseProject();
    const issued = await db.query<{ id: string }>('SELECT id FROM document_folders WHERE "projectId"=$1 AND name=\'Issued\'', [projectId]);
    await workspace.getByLabel("Upload destination folder").selectOption(issued.rows[0]!.id);
    await workspace.getByLabel("File", { exact: true }).setInputFiles({ name: "staff.pdf", mimeType: "application/pdf", buffer: bytes });
    await workspace.getByLabel("Reason").nth(1).fill("Register assigned staff project drawing");
    await workspace.getByRole("button", { name: "Upload and register" }).click();
    await expect(workspace.getByText("staff.pdf")).toBeVisible();
    await useSession(ownerSecret);
    await page.reload();
    await expect(workspace.getByLabel("Document project branch").locator(`option[value="${branchId}"]`)).toHaveCount(1);
    await expect(workspace.getByText("Loading project document access…")).toBeHidden();
    await chooseProject();
    const download = page.waitForEvent("download");
    await workspace.getByRole("listitem").filter({ hasText: "confidential.pdf" }).getByRole("link", { name: "Download" }).click();
    expect((await download).suggestedFilename()).toBe("confidential.pdf");
    await workspace.getByLabel("Reason").last().fill("Remove temporary confidential access");
    await workspace.getByRole("button", { name: /Revoke access.*confidential\.pdf/ }).click();
    await expect(workspace.getByText("Document access revoked.")).toBeVisible();
    await useSession(staffSecret);
    expect((await page.request.get(`/api/v1/documents/files/${document.rows[0]!.id}/stream`)).status()).toBe(403);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  } finally {
    if (!committed) await db.query("ROLLBACK");
    if (ownerAccountId) await db.query('UPDATE sessions SET "revokedAt"=CURRENT_TIMESTAMP WHERE id IN ($1,$2)', [ownerSessionId, staffSessionId]);
    await db.end();
  }
});
