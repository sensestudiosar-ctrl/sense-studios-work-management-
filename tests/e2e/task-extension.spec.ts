import { test, expect } from "@playwright/test";
import { createHash, createHmac, randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";

test("primary owner extension, Owner Team settings and recurring schedule persist after refresh", async ({ page, context, baseURL }, testInfo) => {
  test.setTimeout(90_000);
  test.skip(!process.env.DATABASE_URL, "Dedicated local test database required");
  const url = new URL(process.env.DATABASE_URL!);
  if (!["localhost", "127.0.0.1", "db"].includes(url.hostname) || !url.pathname.endsWith("_test")) throw new Error("Extension fixture requires a dedicated test database");
  const require = createRequire(resolve("apps/api/package.json"));
  const { Client } = require("pg") as typeof import("pg");
  const db = new Client({ connectionString: process.env.DATABASE_URL });
  const suffix = randomUUID();
  const branchId = randomUUID(), teamId = randomUUID(), accountId = randomUUID(), employeeId = randomUUID();
  const ownerSecret = randomBytes(32).toString("base64url"), staffSecret = randomBytes(32).toString("base64url");
  const csrf = (secret: string) => createHmac("sha256", secret).update("csrf").digest("base64url");
  const hash = (value: string) => createHash("sha256").update(value).digest("hex");
  await db.connect();
  try {
    await db.query("BEGIN");
    await db.query("SELECT pg_advisory_xact_lock(6092706)");
    const existingOrg = await db.query<{ id: string }>("SELECT id FROM organizations LIMIT 1");
    const organizationId = existingOrg.rows[0]?.id ?? randomUUID();
    if (!existingOrg.rows[0]) await db.query('INSERT INTO organizations(id,name,"updatedAt") VALUES($1,$2,CURRENT_TIMESTAMP)', [organizationId, "S10 extension browser fixture"]);
    const existingOwner = await db.query<{ id: string }>("SELECT id FROM accounts WHERE kind='OWNER' AND state='ACTIVE' LIMIT 1");
    const ownerId = existingOwner.rows[0]?.id ?? randomUUID();
    if (!existingOwner.rows[0]) {
      await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'OWNER\',\'ACTIVE\',CURRENT_TIMESTAMP)', [ownerId, `extension-owner-${suffix}@example.test`]);
      await db.query('INSERT INTO passkey_credentials(id,"credentialId","accountId","publicKey") VALUES($1,$2,$3,$4),($5,$6,$3,$7)', [randomUUID(), randomUUID(), ownerId, randomBytes(32), randomUUID(), randomUUID(), randomBytes(32)]);
      await db.query('INSERT INTO owner_recovery_codes(id,"accountId","codeHash","acknowledgedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [randomUUID(), ownerId, hash(randomUUID())]);
    }
    await db.query('INSERT INTO branches(id,"organizationId",name,"updatedAt") VALUES($1,$2,$3,CURRENT_TIMESTAMP)', [branchId, organizationId, `S10 extension ${suffix}`]);
    await db.query('INSERT INTO teams(id,"organizationId","branchId",name,"updatedAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP)', [teamId, organizationId, branchId, `S10 extension team ${suffix}`]);
    await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES($1,$2,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP)', [accountId, `extension-${suffix}@example.test`]);
    await db.query('INSERT INTO employees(id,"organizationId","accountId","homeBranchId","homeTeamId","hiredAt","updatedAt") VALUES($1,$2,$3,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP)', [employeeId, organizationId, accountId, branchId, teamId]);
    for (const [account, secret] of [[ownerId, ownerSecret], [accountId, staffSecret]]) await db.query('INSERT INTO sessions(id,"accountId","tokenHash","csrfTokenHash","expiresAt") VALUES($1,$2,$3,$4,CURRENT_TIMESTAMP+interval \'1 hour\')', [randomUUID(), account, hash(secret), hash(csrf(secret))]);
    await db.query("COMMIT");
    const ownerHeaders = { Cookie: `sense_sid=${ownerSecret}`, Origin: baseURL!, "X-CSRF-Token": csrf(ownerSecret) };
    const title = `Extension ${suffix.slice(0, 8)}`;
    const created = await page.request.post("/api/v1/tasks", { headers: ownerHeaders, data: { title, type: "NON_PROJECT", ownerEmployeeId: employeeId, priority: "HIGH", targetDate: "2026-12-01", reason: "Create extension browser task" } });
    expect(created.status()).toBe(201);
    const task = await created.json() as { id: string };
    expect((await page.request.post(`/api/v1/tasks/${task.id}/committed-date`, { headers: ownerHeaders, data: { expectedVersion: 1, committedDueDate: "2026-12-02", reason: "Set original commitment" } })).status()).toBe(201);
    await context.addCookies([{ name: "sense_sid", value: staffSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto(`/?taskId=${task.id}`);
    const workspace = page.locator(".task-workspace");
    const extensions = workspace.getByRole("region", { name: "Deadline extensions" });
    await expect(workspace.getByRole("heading", { name: title })).toBeVisible();
    await extensions.getByLabel("Proposed new date").fill("2026-12-05");
    await extensions.getByRole("combobox", { name: "Approver", exact: true }).selectOption(ownerId);
    await extensions.getByLabel("Reason", { exact: true }).fill("Supplier revised delivery date");
    await extensions.getByRole("button", { name: "Request extension" }).click();
    await expect(extensions.getByText("Pending", { exact: true })).toBeVisible();
    await page.reload();
    await expect(extensions.getByText("Pending", { exact: true })).toBeVisible();
    expect(await db.query('SELECT "committedDueDate"::text AS date FROM tasks WHERE id=$1', [task.id]).then((result) => result.rows[0].date)).toBe("2026-12-02");
    await context.addCookies([{ name: "sense_sid", value: ownerSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.reload();
    await workspace.getByRole("button", { name: new RegExp(`^${title} `) }).click();
    await extensions.getByLabel("Decision reason").fill("Revised supplier commitment approved");
    await workspace.screenshot({ path: testInfo.outputPath("task-extension-approval.png") });
    await extensions.getByRole("button", { name: "Approve extension" }).click();
    await expect(extensions.getByText("Approved", { exact: true })).toBeVisible();
    await page.reload();
    await workspace.getByRole("button", { name: new RegExp(`^${title} `) }).click();
    await expect(workspace.getByRole("heading", { name: title })).toBeVisible();
    await expect(workspace.getByText("Committed due date", { exact: true }).first().locator("..")).toContainText("2026-12-05");
    const history = await db.query('SELECT "newDate"::text AS date,"extensionApprovalId" AS approval FROM task_committed_date_changes WHERE "taskId"=$1 AND "extensionApprovalId" IS NOT NULL', [task.id]);
    expect(history.rows).toEqual([{ date: "2026-12-05", approval: expect.any(String) }]);
    await page.getByRole("button", { name: "Manage organization" }).click();
    const admin = page.locator(".org-admin");
    await admin.locator("#org-reason-branch").fill("Enable Waiting notices for the Team");
    await admin.getByRole("button", { name: `Enable Waiting alerts for S10 extension team ${suffix}`, exact: true }).click();
    await expect(admin.getByRole("button", { name: `Disable Waiting alerts for S10 extension team ${suffix}`, exact: true })).toBeVisible();
    await admin.getByLabel("IANA timezone").fill("UTC");
    await admin.getByRole("button", { name: "Change timezone", exact: true }).click();
    await expect(admin.getByLabel("IANA timezone")).toHaveValue("UTC");
    await page.reload();
    await page.getByRole("button", { name: "Manage organization" }).click();
    await expect(admin.getByRole("button", { name: `Disable Waiting alerts for S10 extension team ${suffix}`, exact: true })).toBeVisible();
    await expect(admin.getByLabel("IANA timezone")).toHaveValue("UTC");
    await admin.locator("#org-reason-branch").fill("Restore approved organization scheduling zone");
    await admin.getByLabel("IANA timezone").fill("Asia/Kolkata");
    await admin.getByRole("button", { name: "Change timezone", exact: true }).click();
    await expect(admin.getByText("Organization settings saved.")).toBeVisible();
    const recurringTitle = `Recurring ${suffix.slice(0, 8)}`;
    const createdRecurring = await page.request.post("/api/v1/tasks", { headers: ownerHeaders, data: { title: recurringTitle, type: "RECURRING", ownerEmployeeId: employeeId, priority: "MEDIUM", targetDate: "2026-12-01", reason: "Create recurring browser source" } });
    expect(createdRecurring.status()).toBe(201);
    const recurring = await createdRecurring.json() as { id: string };
    await context.addCookies([{ name: "sense_sid", value: staffSecret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto(`/?taskId=${recurring.id}`);
    await expect(workspace.getByRole("heading", { name: recurringTitle })).toBeVisible();
    const recurrence = workspace.locator(".task-recurrence");
    await recurrence.getByRole("combobox", { name: "Frequency", exact: true }).selectOption("MONTHLY");
    await recurrence.getByLabel("First occurrence date").fill("2026-12-31");
    await recurrence.getByLabel("Reason", { exact: true }).fill("Monthly team check at month end");
    await recurrence.getByRole("button", { name: "Save recurrence rule" }).click();
    await expect(recurrence.getByText("Monthly", { exact: true }).first()).toBeVisible();
    await page.reload();
    await expect(recurrence.getByText("Asia/Kolkata", { exact: true })).toBeVisible();
    await recurrence.getByLabel("Reason for pausing").fill("Pause scheduled generation for review");
    await recurrence.getByRole("button", { name: "Pause recurrence" }).click();
    await expect(recurrence.getByText("Paused", { exact: true }).first()).toBeVisible();
    await recurrence.getByLabel("Reason for resuming").fill("Resume the approved monthly schedule");
    await recurrence.getByRole("button", { name: "Resume recurrence" }).click();
    await page.reload();
    await expect(recurrence.getByText("Active", { exact: true })).toBeVisible();
    expect(await db.query('SELECT count(*)::int AS count FROM task_recurrence_changes h JOIN task_recurrence_rules r ON r.id=h."ruleId" WHERE r."sourceTaskId"=$1', [recurring.id]).then((result) => result.rows[0].count)).toBe(3);
    await workspace.screenshot({ path: testInfo.outputPath("task-recurrence-schedule.png") });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  } finally {
    await db.query('UPDATE sessions SET "revokedAt"=CURRENT_TIMESTAMP WHERE "tokenHash" IN ($1,$2)', [hash(ownerSecret), hash(staffSecret)]);
    await db.end();
  }
});
