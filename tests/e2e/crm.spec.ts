import { test, expect } from "@playwright/test";
import { createHash, createHmac, randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { resolve } from "node:path";

test("granted staff persists the CRM pipeline and returning Lost enquiry across refresh", async ({ page, context, baseURL }) => {
  test.skip(!process.env.DATABASE_URL, "Dedicated local test database required");
  const url = new URL(process.env.DATABASE_URL!);
  if (!["localhost", "127.0.0.1", "db"].includes(url.hostname) || !url.pathname.endsWith("_test")) throw new Error("CRM browser fixture requires dedicated test database");
  const require = createRequire(resolve("apps/api/package.json"));
  const { Client } = require("pg") as typeof import("pg");
  const db = new Client({ connectionString: process.env.DATABASE_URL });
  const secret = randomBytes(32).toString("base64url");
  const csrf = createHmac("sha256", secret).update("csrf").digest("base64url");
  const hash = (value: string) => createHash("sha256").update(value).digest("hex");
  const branchId = randomUUID(), otherBranchId = randomUUID(), teamId = randomUUID(), accountId = randomUUID(), employeeId = randomUUID();
  const title = `CRM enquiry ${randomUUID().slice(0, 8)}`;
  let organizationId: string;
  await db.connect();
  try {
    await db.query("BEGIN");
    await db.query("SELECT pg_advisory_xact_lock(6092706)");
    const org = await db.query<{ id: string }>("SELECT id FROM organizations LIMIT 1");
    organizationId = org.rows[0]?.id ?? randomUUID();
    if (!org.rows[0]) await db.query('INSERT INTO organizations(id,name,"updatedAt") VALUES ($1,$2,CURRENT_TIMESTAMP)', [organizationId, "CRM browser fixture"]);
    for (const [id, name] of [[branchId, `CRM allowed ${branchId}`], [otherBranchId, `CRM hidden ${otherBranchId}`]]) await db.query('INSERT INTO branches(id,"organizationId",name,"updatedAt") VALUES ($1,$2,$3,CURRENT_TIMESTAMP)', [id, organizationId, name]);
    await db.query('INSERT INTO teams(id,"organizationId","branchId",name,"updatedAt") VALUES ($1,$2,$3,$4,CURRENT_TIMESTAMP)', [teamId, organizationId, branchId, "CRM fixture team"]);
    await db.query('INSERT INTO accounts(id,"normalizedEmail",kind,state,"updatedAt") VALUES ($1,$2,\'STAFF\',\'ACTIVE\',CURRENT_TIMESTAMP)', [accountId, `crm-${accountId}@example.test`]);
    await db.query('INSERT INTO employees(id,"organizationId","accountId","homeBranchId","homeTeamId","hiredAt","updatedAt") VALUES ($1,$2,$3,$4,$5,CURRENT_DATE,CURRENT_TIMESTAMP)', [employeeId, organizationId, accountId, branchId, teamId]);
    for (const key of ["lead.view", "lead.create", "lead.edit", "lead.stage_change", "lead.activity_create"]) await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind","branchId",reason) VALUES ($1,$2,$3,$4,\'ALLOW\',\'BRANCH\',$5,$6)', [randomUUID(), organizationId, employeeId, key, branchId, "CRM browser fixture grant"]);
    await db.query('INSERT INTO sessions(id,"accountId","tokenHash","csrfTokenHash","expiresAt") VALUES ($1,$2,$3,$4,CURRENT_TIMESTAMP+interval \'1 hour\')', [randomUUID(), accountId, hash(secret), hash(csrf)]);
    await db.query("COMMIT");
    await context.addCookies([{ name: "sense_sid", value: secret, url: baseURL!, httpOnly: true, sameSite: "Strict" }]);
    await page.goto("/");
    const crm = page.locator(".crm");
    await expect(crm.getByRole("heading", { name: "Leads and clients" })).toBeVisible();
    await expect(crm.getByRole("button", { name: "New lead", exact: true })).toBeVisible();
    expect(await crm.getByLabel("CRM branch").locator("option").allTextContents()).not.toContain(`CRM hidden ${otherBranchId}`);
    const forbidden = await page.request.get(`/api/v1/crm/leads?branchId=${otherBranchId}`);
    expect(forbidden.status()).toBe(403);
    await crm.getByRole("button", { name: "New lead", exact: true }).click();
    const form = page.locator(".crm-modal");
    await form.getByLabel("Title", { exact: true }).fill(title);
    await form.getByLabel("Contact name", { exact: true }).fill("CRM contact");
    await form.getByRole("combobox", { name: "Source", exact: true }).selectOption({ label: "Referral" });
    await form.getByLabel("Creation reason").fill("New browser enquiry");
    await form.getByRole("button", { name: "Create lead", exact: true }).click();
    await expect(form).toHaveCount(0);
    await crm.getByRole("button", { name: new RegExp(title) }).click();
    await crm.getByRole("combobox", { name: "New stage", exact: true }).selectOption("PROPOSAL");
    await crm.getByLabel("Reason for Lost, skipped or backward move").fill("Already discussed before capture");
    await crm.getByRole("button", { name: "Save stage" }).click();
    await expect(crm.getByText("Skipped stages: Contacted, Meeting Discussion")).toBeVisible();
    await crm.getByLabel("Note", { exact: true }).fill("Browser interaction evidence");
    await crm.getByRole("button", { name: "Add activity" }).click();
    await expect(crm.locator(".crm-timeline").getByText("Browser interaction evidence")).toBeVisible();
    await crm.getByRole("combobox", { name: "New stage", exact: true }).selectOption("LOST");
    await crm.getByLabel("Reason for Lost, skipped or backward move").fill("Client postponed browser fixture");
    await crm.getByRole("button", { name: "Save stage" }).click();
    await expect(crm.getByRole("combobox", { name: "New stage", exact: true })).toHaveCount(0);
    await page.reload();
    await crm.getByRole("button", { name: new RegExp(title) }).click();
    await expect(crm.getByText(/Client postponed browser fixture/).first()).toBeVisible();
    await expect(crm.locator(".crm-timeline").getByText("Browser interaction evidence")).toBeVisible();
    await crm.getByRole("button", { name: /returning|renewed|linked/i }).click();
    await form.getByLabel("Title", { exact: true }).fill(`${title} renewal`);
    await form.getByLabel("Contact name", { exact: true }).fill("CRM contact");
    await form.getByRole("combobox", { name: "Source", exact: true }).selectOption({ label: "Referral" });
    await form.getByLabel("Creation reason").fill("Client renewed enquiry");
    await form.getByRole("button", { name: "Create lead", exact: true }).click();
    await expect(form).toHaveCount(0);
    const rows = await db.query<{ id: string; stage: string; priorLostLeadId: string | null }>('SELECT id,stage,"priorLostLeadId" FROM leads WHERE "branchId"=$1 ORDER BY "createdAt"', [branchId]);
    expect(rows.rows).toHaveLength(2);
    expect(rows.rows[0]?.stage).toBe("LOST");
    expect(rows.rows[1]).toMatchObject({ stage: "NEW", priorLostLeadId: rows.rows[0]?.id });
    await expect(crm.getByText("Lead source settings", { exact: true })).toHaveCount(0);
    const deniedSource = await page.request.post("/api/v1/crm/sources", { headers: { Origin: baseURL!, "x-csrf-token": csrf }, data: { name: "Denied fixture", reason: "No source grant" } });
    expect(deniedSource.status()).toBe(403);
    await db.query('INSERT INTO employee_permission_overrides(id,"organizationId","employeeId","permissionKey",effect,"scopeKind",reason) VALUES ($1,$2,$3,$4,\'ALLOW\',\'ORGANIZATION\',$5)', [randomUUID(), organizationId, employeeId, "crm_source.manage", "Source manager browser fixture"]);
    await page.reload();
    await crm.getByText("Lead source settings", { exact: true }).click();
    const settings = crm.locator(".crm-sources");
    const sourceName = `Partner ${accountId.slice(0, 8)}`;
    await settings.getByLabel("New source name").fill(sourceName);
    await settings.getByLabel("Reason", { exact: true }).fill("Track partner enquiry channel");
    await settings.getByRole("button", { name: "Add source" }).click();
    const sourceItem = settings.getByRole("listitem").filter({ has: page.getByText(sourceName, { exact: true }) });
    await expect(sourceItem).toBeVisible();
    await sourceItem.getByLabel("Reason to deactivate").fill("Retire partner channel");
    await sourceItem.getByRole("button", { name: "Deactivate" }).click();
    await expect(sourceItem.getByText(/Inactive/)).toBeVisible();
    await crm.getByRole("button", { name: "New lead", exact: true }).click();
    await expect(form.getByRole("combobox", { name: "Source", exact: true }).locator("option").filter({ hasText: sourceName })).toHaveCount(0);
    await form.getByRole("button", { name: "Cancel" }).click();
    const sourceEvidence = await db.query<{ active: boolean; eventCount: string }>('SELECT s.active, (SELECT count(*) FROM audit_events a WHERE a."subjectId"=s.id::text) AS "eventCount" FROM crm_sources s WHERE s."organizationId"=$1 AND s.name=$2', [organizationId, sourceName]);
    expect(sourceEvidence.rows[0]).toMatchObject({ active: false, eventCount: "2" });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  } finally {
    // Preserve append-only evidence; only revoke this fixture session.
    await db.query('UPDATE sessions SET "revokedAt"=CURRENT_TIMESTAMP WHERE "accountId"=$1', [accountId]);
    await db.end();
  }
});
